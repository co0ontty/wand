// Android's launcher vectors are the source of truth. Native repositories keep
// local snapshots so their standalone builds never require the parent checkout.
import assert from "node:assert/strict";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { deflateSync, inflateSync } from "node:zlib";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");
const read = (path) => readFileSync(resolve(root, path), "utf8");
const foreground = read("android/app/src/main/res/drawable/ic_launcher_foreground.xml");
const background = read("android/app/src/main/res/drawable/ic_launcher_background.xml");
const paths = [...foreground.matchAll(/android:fillColor="(#[A-Fa-f0-9]{6})"\s+android:pathData="([^"]+)"/g)]
  .map(([, fill, d]) => ({ fill, d }));
assert.equal(paths.length, 6, "Expected Android's six-color pixel-cat artwork");
const logo = {
  viewport: Number(foreground.match(/android:viewportWidth="(\d+)"/)[1]),
  inset: Number(foreground.match(/android:translateX="(\d+)"/)[1]),
  background: background.match(/android:fillColor="(#[A-Fa-f0-9]{6})"/)[1],
  paths,
};
assert.equal(logo.viewport, Number(foreground.match(/android:viewportHeight="(\d+)"/)[1]));
assert.equal(logo.inset, Number(foreground.match(/android:translateY="(\d+)"/)[1]));

const rectangles = paths.flatMap(({ fill, d }) => {
  // Each Android path consists only of clockwise rectangles on the pixel grid.
  const matches = [...d.matchAll(/M(\d+),(\d+)h(\d+)v(\d+)h-(\d+)z/g)];
  assert.equal(matches.map(m => m[0]).join(" "), d, "Unsupported Android path geometry");
  return matches.map(([, x, y, width, height, back]) => {
    assert.equal(width, back);
    return { x: Number(x), y: Number(y), width: Number(width), height: Number(height), fill };
  });
});

function pngContent(data) {
  try {
    const parts = [data.subarray(0, 8)];
    const compressed = [];
    for (let offset = 8; offset < data.length;) {
      const length = data.readUInt32BE(offset);
      const end = offset + 8 + length;
      const type = data.subarray(offset + 4, offset + 8);
      const content = data.subarray(offset + 8, end);
      if (crc32(data.subarray(offset + 4, end)) !== data.readUInt32BE(end)) return null;
      if (type.toString() === "IDAT") compressed.push(content);
      else parts.push(type, content);
      offset = end + 4;
    }
    return Buffer.concat([...parts, inflateSync(Buffer.concat(compressed))]);
  } catch {
    return null;
  }
}

function emit(path, content) {
  const file = resolve(root, path);
  const expected = Buffer.from(content);
  if (existsSync(file)) {
    const actual = readFileSync(file);
    // zlib versions can encode identical pixels differently. Validate PNG
    // checksums and compare decoded content so --check is runtime-independent.
    if (actual.equals(expected) || (path.endsWith(".png")
      && pngContent(actual)?.equals(pngContent(expected)))) return;
  }
  if (check) throw new Error(`Stale brand asset: ${path}; run npm run sync:brand-assets`);
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, expected);
  console.log(`[brand] ${path}`);
}

const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${logo.viewport} ${logo.viewport}"><rect width="${logo.viewport}" height="${logo.viewport}" rx="24" fill="${logo.background}"/><g transform="translate(${logo.inset} ${logo.inset})">${paths.map(({ fill, d }) => `<path fill="${fill}" d="${d}"/>`).join("")}</g></svg>\n`;
const json = JSON.stringify(logo, null, 2) + "\n";
emit("src/web-ui/brand-logo-data.ts", "// Generated from Android launcher vectors by npm run sync:brand-assets. Do not edit.\nexport const WAND_BRAND = " + json.trim() + " as const;\n");
emit("assets/branding/wand-logo.svg", svg);
emit("browser-extension/icons/wand.svg", svg);
for (const platform of ["ios", "macos"]) {
  emit(`${platform}/scripts/generate-icons.swift`, read("assets/branding/generate-icons.swift")
    .replace("let isIOS = true // Set per platform by sync-brand-assets.", `let isIOS = ${platform === "ios"} // Generated by sync-brand-assets; edit the shared renderer instead.`));
  emit(`${platform}/scripts/wand-logo.json`, json);
  const catalogs = [`${platform}/Wand/Assets.xcassets`];
  if (platform === "ios") {
    catalogs.push("ios/WandWidgets/Assets.xcassets");
    emit("ios/WandWidgets/Assets.xcassets/Contents.json", JSON.stringify({ info: { author: "xcode", version: 1 } }, null, 2) + "\n");
  }
  for (const catalog of catalogs) {
    emit(`${catalog}/WandLogo.imageset/wand-logo.svg`, svg);
    emit(`${catalog}/WandLogo.imageset/Contents.json`, JSON.stringify({
      images: [{ filename: "wand-logo.svg", idiom: "universal" }],
      info: { author: "xcode", version: 1 },
      properties: { "preserves-vector-representation": true, "template-rendering-intent": "original" },
    }, null, 2) + "\n");
  }
}

// Notification icons must be monochrome. Leave eyes/nose transparent instead of
// flattening the whole face into a white blob; launcher artwork stays untouched.
const silhouette = paths.filter(({ fill }) => !["#FFFFFF", "#7EC88B", "#F28B9A"].includes(fill))
  .map(({ d }) => d).join(" ");
emit("android/app/src/main/res/drawable/ic_notification.xml", `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated from the launcher pixel cat by npm run sync:brand-assets. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="60"
    android:viewportHeight="60">
    <path android:fillColor="#FFFFFF" android:pathData="${silhouette}" />
</vector>
`);

// Small, deterministic RGBA PNGs for MV3, whose manifest does not accept SVG.
// No canvas, browser, native binary, font, or network dependency is needed.
function crc32(bytes) {
  let crc = 0xffffffff;
  for (const byte of bytes) {
    crc ^= byte;
    for (let bit = 0; bit < 8; bit++) crc = (crc >>> 1) ^ ((crc & 1) ? 0xedb88320 : 0);
  }
  return (crc ^ 0xffffffff) >>> 0;
}
function chunk(name, data) {
  const type = Buffer.from(name);
  const size = Buffer.alloc(4);
  size.writeUInt32BE(data.length);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(Buffer.concat([type, data])));
  return Buffer.concat([size, type, data, crc]);
}
function rgb(hex) {
  return [1, 3, 5].map(offset => Number.parseInt(hex.slice(offset, offset + 2), 16));
}
function png(size) {
  const pixels = Buffer.alloc(size * (size * 4 + 1));
  const colors = new Map([logo.background, ...paths.map(path => path.fill)].map(color => [color, rgb(color)]));
  for (let y = 0; y < size; y++) {
    for (let x = 0; x < size; x++) {
      const total = [0, 0, 0, 0];
      // Four samples per axis antialias the rounded tile at toolbar sizes.
      for (let sy = 0; sy < 4; sy++) for (let sx = 0; sx < 4; sx++) {
        const vx = (x + (sx + .5) / 4) * logo.viewport / size;
        const vy = (y + (sy + .5) / 4) * logo.viewport / size;
        const dx = Math.max(24 - vx, vx - (logo.viewport - 24), 0);
        const dy = Math.max(24 - vy, vy - (logo.viewport - 24), 0);
        if (dx * dx + dy * dy > 24 * 24) continue;
        const rect = rectangles.find(r => vx >= r.x + logo.inset && vx < r.x + logo.inset + r.width
          && vy >= r.y + logo.inset && vy < r.y + logo.inset + r.height);
        const color = colors.get(rect?.fill ?? logo.background);
        for (let channel = 0; channel < 3; channel++) total[channel] += color[channel];
        total[3]++;
      }
      const offset = y * (size * 4 + 1) + 1 + x * 4;
      if (total[3]) {
        for (let c = 0; c < 3; c++) pixels[offset + c] = Math.round(total[c] / total[3]);
        pixels[offset + 3] = Math.round(total[3] * 255 / 16);
      }
    }
  }
  const header = Buffer.alloc(13);
  header.writeUInt32BE(size, 0);
  header.writeUInt32BE(size, 4);
  header[8] = 8;
  header[9] = 6;
  return Buffer.concat([Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]),
    chunk("IHDR", header), chunk("IDAT", deflateSync(pixels)), chunk("IEND", Buffer.alloc(0))]);
}
for (const size of [16, 32, 48, 128]) emit(`browser-extension/icons/wand-${size}.png`, png(size));
console.log(`[brand] Android pixel-cat assets ${check ? "verified" : "synchronized"}`);
