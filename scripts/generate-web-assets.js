import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { gzipSync } from "node:zlib";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { minifyJs, minifyCss } from "./minify-web-assets.js";
import { buildThemePreload } from "./theme-preload.js";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");
const contentDir = path.join(root, "src", "web-ui", "content");
const outFile = path.join(root, "src", "web-ui", "embedded-assets.ts");

const assets = [
  ["scriptsJs", "scripts.js", "application/javascript"],
  ["stylesCss", "styles.css", "text/css; charset=utf-8"],
  ["xtermJs", path.join("vendor", "xterm", "xterm.bundle.js"), "application/javascript"],
  ["xtermCss", path.join("vendor", "xterm", "xterm.css"), "text/css; charset=utf-8"],
  ["qrcodeJs", path.join("vendor", "qrcode", "qrcode.bundle.js"), "application/javascript"],
  // 按需加载的 AI 团队脚本，bundle-browser.js 已按生产模式 minify，这里原样内嵌。
  ["aiTeamsJs", "ai-teams.js", "application/javascript"],
  ["plushAvatarJs", "plush-avatar.js", "application/javascript"],
];

const moduleManifest = JSON.parse(readFileSync(path.join(contentDir, "module-manifest.json"), "utf8"));
const moduleContents = Object.fromEntries(moduleManifest.files.map(file => [file, readFileSync(path.join(contentDir, file))]));
const browserModules = Object.fromEntries(Object.entries(moduleContents).map(([file, content]) => [file,
  gzipSync(content, { level: 9 }).toString("base64"),
]));
const themePreload = minifyJs(await buildThemePreload(root));
const entries = {};
const artifactHashes = {};
const sha256 = content => createHash("sha256").update(content).digest("hex");
for (const [key, relPath, contentType] of assets) {
  let content = readFileSync(path.join(contentDir, relPath));
  if (relPath === "scripts.js") {
    content = Buffer.from(minifyJs(content.toString("utf8")), "utf8");
  } else if (relPath === "styles.css") {
    // Must mirror src/web-ui/styles.ts: Tailwind utilities first, then the
    // business CSS. Ant Design/X component styles are installed at runtime.
    const tailwind = readFileSync(path.join(contentDir, "tailwind.css"), "utf8");
    content = Buffer.from(minifyCss(`${tailwind}\n${content.toString("utf8")}`), "utf8");
  }
  artifactHashes[relPath] = sha256(content);
  const assetHash = createHash("md5").update(content).digest("hex").slice(0, 8);
  entries[key] = {
    base64: gzipSync(content, { level: 9 }).toString("base64"),
    hash: assetHash,
    contentType,
  };
}

// Bind the budget, generated bytes and esbuild graph to one immutable record.
// A later check/build may replace the legacy latest paths; archived evidence
// remains attributable to the exact built package instead of the latest run.
for (const [file, content] of Object.entries(moduleContents)) {
  if (moduleManifest.integrity?.[file] !== sha256(content)) throw new Error(`Module integrity mismatch: ${file}`);
  artifactHashes[file] = sha256(content);
}
artifactHashes["theme.js"] = sha256(themePreload);
const graphDirectory = path.join(root, "output/web-ui-library-migration/bundle-graphs");
const graphNames = ["main.js.json", "scripts.js.json", "ai-teams.js.json", "plush-avatar.js.json"];
const graphContents = Object.fromEntries(graphNames.map(name => [name, readFileSync(path.join(graphDirectory, name), "utf8")]));
if (JSON.parse(graphContents["main.js.json"]).wandBuild?.id !== moduleManifest.buildId) throw new Error("Browser graph/manifest build identity mismatch");
const evidence = { moduleBuildId: moduleManifest.buildId, node: process.version, zlib: process.versions.zlib,
  artifacts: artifactHashes, graphs: Object.fromEntries(Object.entries(graphContents).map(([name, content]) => [name, sha256(content)])) };
const buildIdentity = { id: sha256(JSON.stringify(evidence)).slice(0, 16), ...evidence };
const archive = path.join(root, "output/web-ui-library-migration/builds", buildIdentity.id);
mkdirSync(path.join(archive, "bundle-graphs"), { recursive: true });
for (const [name, content] of Object.entries(graphContents)) writeFileSync(path.join(archive, "bundle-graphs", name), content);
writeFileSync(path.join(archive, "build-manifest.json"), JSON.stringify({ ...buildIdentity, manifest: moduleManifest }, null, 2));

const source = `// Generated by scripts/generate-web-assets.js. Do not edit by hand.
import { Buffer } from "node:buffer";
import { gunzipSync } from "node:zlib";

function decode(value: string): string {
  return gunzipSync(Buffer.from(value, "base64")).toString("utf8");
}

export const EMBEDDED_WEB_ASSETS = {
  buildIdentity: ${JSON.stringify(buildIdentity)},
  browserModuleManifest: ${JSON.stringify(moduleManifest)},
  browserModules: Object.fromEntries(Object.entries(${JSON.stringify(browserModules)}).map(([name, value]) => [name, decode(value)])) as Record<string, string>,
  themePreloadJs: decode(${JSON.stringify(gzipSync(themePreload).toString("base64"))}),
  scriptsJs: decode(${JSON.stringify(entries.scriptsJs.base64)}),
  aiTeamsJs: decode(${JSON.stringify(entries.aiTeamsJs.base64)}),
  plushAvatarJs: decode(${JSON.stringify(entries.plushAvatarJs.base64)}),
  stylesCss: decode(${JSON.stringify(entries.stylesCss.base64)}),
  vendor: {
    "/vendor/xterm/xterm.bundle.js": {
      content: decode(${JSON.stringify(entries.xtermJs.base64)}),
      contentType: ${JSON.stringify(entries.xtermJs.contentType)},
      hash: ${JSON.stringify(entries.xtermJs.hash)},
    },
    "/vendor/xterm/xterm.css": {
      content: decode(${JSON.stringify(entries.xtermCss.base64)}),
      contentType: ${JSON.stringify(entries.xtermCss.contentType)},
      hash: ${JSON.stringify(entries.xtermCss.hash)},
    },
    "/vendor/qrcode/qrcode.bundle.js": {
      content: decode(${JSON.stringify(entries.qrcodeJs.base64)}),
      contentType: ${JSON.stringify(entries.qrcodeJs.contentType)},
      hash: ${JSON.stringify(entries.qrcodeJs.hash)},
    },
  },
} as const;

export type EmbeddedVendorAssetPath = keyof typeof EMBEDDED_WEB_ASSETS.vendor;
`;

writeFileSync(outFile, source, "utf8");
console.log(`[generate-web-assets] wrote ${path.relative(root, outFile)}`);
