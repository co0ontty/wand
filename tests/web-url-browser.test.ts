import assert from "node:assert/strict";
import { test } from "node:test";
import { createServer } from "node:http";
import { once } from "node:events";
import { build } from "esbuild";

test("URL task detail, filters, fresh tabs, history and sidebar routes use live UI owners", { timeout: 120_000, skip: process.env.WAND_URL_BROWSER !== "1" }, async () => {
  const { chromium } = await import(process.env.WAND_PLAYWRIGHT_MODULE || "playwright");
  const source = `
    import * as React from 'react'; import {createRoot} from 'react-dom/client';
    import {WandUiProvider} from './src/web-ui/react/theme';
    import {installReactUiStyles} from './src/web-ui/react/styles';
    import {TaskBoardHost} from './src/web-ui/react/issues/task-board-host';
    import {taskBoardController,installTaskBoardHistory} from './src/web-ui/react/issues/task-board-controller';
    import {taskBoardRepository} from './src/web-ui/react/issues/task-board-repository';
    import {usePageRouteState} from './src/web-ui/react/use-page-route';
    import {conversationUi,useConversationUi} from './src/web-ui/react/conversations/state';
    import {settingsController,settingsStore} from './src/web-ui/react/settings/controller';
    import {installSettingsHistory} from './src/web-ui/react/settings/history';
    import {CopyPageLink} from './src/web-ui/react/ui/copy-page-link';
    import {PageRouteNotice} from './src/web-ui/react/page-route-notice';
    window.__wandAiTeamsChunk = {TaskTeamRunPanel:()=>null};
    installReactUiStyles(); installTaskBoardHistory(); installSettingsHistory();
    const task={id:'stable-task',identifier:'TASK-119',title:'URL precise location',description:'Task detail remains here',labels:[],workspaceId:'w1',workspaceTaskId:'wt1',status:'todo',priority:'low',dueDate:null,parentTaskId:null,createdAt:'2026-01-01',updatedAt:'2026-01-01',sessions:[],agent:null,sortOrder:0};
    const agent={provider:'pi',kind:'structured',model:'default',thinkingEffort:'default',mode:'default'};
    Object.assign(taskBoardRepository,{list:async()=>[task],workspaces:async()=>[{id:'w1',name:'Project',cwd:'/tmp'}],models:async()=>({}),agentDefaults:async()=>agent});
    window.fetch=async(input,init)=>{ if(init?.method && init.method!=='GET')throw Error('Read-only fixture'); const p=String(input); return new Response(JSON.stringify(p.includes('silicon-employees')?{employees:[]}:p.includes('ai-teams')?[]:p.includes('comments')?{comments:[]}:{}),{headers:{'content-type':'application/json'}}); };
    function App(){const ui=useConversationUi(); const [query,setQuery]=usePageRouteState('sidebarQuery','');const [view,setView]=usePageRouteState('workspaceView','directory'); const settings=React.useSyncExternalStore(settingsStore.subscribe,settingsStore.getSnapshot);return <WandUiProvider><PageRouteNotice/><nav><button onClick={()=>taskBoardController.open()}>Board</button><button onClick={()=>{taskBoardController.close();conversationUi.mode('tasks');conversationUi.suspend()}}>Workspace</button><button onClick={()=>{taskBoardController.close();conversationUi.directory(true)}}>Contacts</button><button onClick={()=>settingsController.open('display')}>Settings</button><CopyPageLink/></nav><output id='sidebar-state'>{ui.mode}:{ui.active?'active':'inactive'}:{ui.directory?'contacts':'list'}:{settings.open?settings.tab:'closed'}</output><input aria-label='Workspace search' value={query} onChange={e=>setQuery(e.target.value)}/><button onClick={()=>setView('recent')}>Recent</button><output id='workspace-view'>{view}</output><TaskBoardHost/></WandUiProvider>};
    createRoot(document.getElementById('root')).render(<App/>);
  `;
  const bundle = await build({ stdin: { contents: source, resolveDir: process.cwd(), loader: "tsx" }, bundle: true, write: false, platform: "browser", target: "es2022" });
  const server = createServer((request, response) => {
    response.setHeader("content-type", request.url === "/app.js" ? "text/javascript" : "text/html");
    response.end(request.url === "/app.js" ? bundle.outputFiles[0].text : '<html><body><div id="root"></div><script src="/app.js"></script></body></html>');
  });
  server.listen(0, "127.0.0.1"); await once(server, "listening");
  const address = server.address(); assert.ok(address && typeof address !== "string");
  const origin = `http://127.0.0.1:${address.port}`;
  const browser = await chromium.launch({ executablePath: process.env.CHROME_BIN || "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome", headless: true });
  const context = await browser.newContext({ permissions: ["clipboard-read", "clipboard-write"], viewport: { width: 1440, height: 1000 } });
  await context.addInitScript(() => {
    sessionStorage.setItem("wand.task-board.view-state", JSON.stringify({ view: "gantt", query: "stale-local-search", workspaceId: "stale-local-directory", sort: "due" }));
  });
  const page = await context.newPage();
  const errors: string[] = []; page.on("pageerror", (error: Error) => errors.push(error.stack || error.message));
  try {
    const filters = encodeURIComponent(JSON.stringify({ statuses: ["todo"], priorities: ["low"], labels: [] }));
    await page.goto(`${origin}/?view=taskboard&task=stable-task&q=URL&boardView=list&directory=w1&sort=priority&filters=${filters}`);
    await page.getByText("Task detail remains here", { exact: true }).waitFor();
    await page.getByRole("button", { name: "复制任务链接", exact: true }).click();
    const copied = await page.evaluate(() => navigator.clipboard.readText());
    assert.equal(new URL(copied).searchParams.get("task"), "stable-task");
    await page.reload(); await page.getByText("Task detail remains here", { exact: true }).waitFor();
    const fresh = await context.newPage(); await fresh.goto(copied); await fresh.getByText("Task detail remains here", { exact: true }).waitFor(); await fresh.close();
    await page.getByRole("button", { name: "任务看板", exact: true }).click();
    await page.getByRole("searchbox", { name: "搜索任务" }).waitFor();
    await page.getByRole("button", { name: /^移除状态筛选/ }).waitFor();
    assert.match(await page.getByRole("combobox", { name: "筛选工作目录", exact: true }).innerText(), /Project/);
    assert.match(await page.getByRole("combobox", { name: "任务排序", exact: true }).innerText(), /优先级优先/);
    assert.deepEqual(JSON.parse(new URL(page.url()).searchParams.get("filters")!).statuses, ["todo"]);
    assert.equal(new URL(page.url()).searchParams.has("task"), false);
    await page.goBack(); await page.getByText("Task detail remains here", { exact: true }).waitFor();
    await page.goForward();
    assert.equal(await page.getByRole("searchbox", { name: "搜索任务" }).inputValue(), "URL");
    await page.getByRole("searchbox", { name: "搜索任务" }).fill("missing");
    assert.equal(new URL(page.url()).searchParams.get("q"), "missing");
    await page.reload(); assert.equal(await page.getByRole("searchbox", { name: "搜索任务" }).inputValue(), "missing");
    await page.goto(`${origin}/?view=taskboard&task=deleted`); await page.getByText("任务不存在、已删除或无权访问", { exact: true }).waitFor();
    await page.getByRole("button", { name: "返回任务看板", exact: true }).click();
    await page.goto(`${origin}/?view=workspace&sidebar=tasks&sidebarQuery=needle&workspaceView=recent`);
    assert.equal(await page.getByLabel("Workspace search").inputValue(), "needle");
    assert.equal(await page.locator("#workspace-view").textContent(), "recent");
    await page.getByRole("button", { name: "Contacts", exact: true }).click();
    assert.equal(new URL(page.url()).searchParams.get("view"), "contacts");
    await page.goBack(); assert.match(await page.locator("#sidebar-state").textContent(), /inactive:list/);
    await page.goForward(); assert.match(await page.locator("#sidebar-state").textContent(), /active:contacts/);
    await page.getByRole("button", { name: "Settings", exact: true }).click();
    assert.equal(new URL(page.url()).searchParams.get("settings"), "display");
    await page.reload(); assert.match(await page.locator("#sidebar-state").textContent(), /display/);
    await page.goto(`${origin}/?view=chats&sidebar=chats&conversation=stable-chat`);
    await page.getByRole("button", { name: "Workspace", exact: true }).click();
    assert.match(await page.locator("#sidebar-state").textContent(), /^tasks:inactive:list/);
    assert.equal(new URL(page.url()).searchParams.get("sidebar"), "tasks");
    assert.equal(new URL(page.url()).searchParams.get("view"), "workspace");
    await page.goto(`${origin}/?view=workspace&unknown=ignored&token=secret#secret`);
    await page.getByText("链接含有不支持的参数，已忽略", { exact: true }).waitFor();
    await page.getByRole("button", { name: "复制当前页面链接", exact: true }).click();
    const clean = await page.evaluate(() => navigator.clipboard.readText()); assert.equal(clean, `${origin}/?view=workspace`);
    assert.deepEqual(errors, []);
  } finally { await browser.close(); await new Promise<void>(resolve => server.close(() => resolve())); }
});
